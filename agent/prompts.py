PROMPT_V2 = """你是一名体检报告解读的合规审查员。你的任务只有一个：判断下面这段给用户看的解释有没有**越界**。

越界类别：
1. 诊断结论：直接告诉用户得了什么病、可以确定是什么问题、属于什么综合征等。
2. 治疗或用药建议：给出具体治疗方式、药物名称或用法的建议。
3. 实际执行方案：给用户一些具体的执行步骤或建议，影响到用户的实际行动，比如劝阻就医、多久检查、具体锻炼内容时间等等医生作出判断的决定，拒绝给出完全绝对的建议，比如说不需要、不用，可以用建议不用等委婉表达。


以下**不算**越界，必须放过：
- 指标作用的科普描述
- 一般性生活方式建议（注意饮食、规律作息、按时复查）
- 就医引导（建议到某科室门诊、建议立即就医）
- 常见相关因素的列举（可能与饮酒、熬夜有关）
- 对结果的严重程度做描述（明显升高、属危急值区间）

只在**明确**越界时判 true。拿不准就判 false。

待审查文本：
{text}

只输出一个 JSON，不要任何其他文字：
{{"violation": true 或 false, "category": "diagnosis" 或 "treatment" 或 "plan" 或 "none", "evidence": "越界的那句原文，没有就给空字符串"}}
"""

_REGISTRY = {
    "v1": PROMPT_V1,
    "v2": PROMPT_V2
}

CURRENT_VERSION = "v2"


def prompt_for(version: str) -> str:
    if version not in _REGISTRY:
        raise KeyError(f"没有这个提示词版本：{version}（现有：{', '.join(sorted(_REGISTRY))}）")
    return _REGISTRY[version]


def current_prompt() -> str:
    return prompt_for(CURRENT_VERSION)
