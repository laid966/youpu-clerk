"""★ 这是你的文件 ★ 对话层的**策略**：上下文管理、压缩口径、留存。

机制在 `agent/chat.py`（存储、组装、压缩执行器、CLI）。
**这里放的全是判断**——每一个都影响"用户感受到什么"和"要花多少钱"。

---

## 你要定的五件事（按重要性排）

### ① 压缩触发条件 —— 最影响成本与体验

上下文不能无限增长，否则：
- **成本线性上升**（每轮都要把全部历史重新发一遍）
- **延迟上升**
- **注意力稀释**（模型被无关的旧对话带偏）

所以要有"什么时候开始压缩"的阈值。

### ② 压缩时**永不丢弃**什么

这一条比 ① 重要得多。压缩一旦丢错东西，会出**很隐蔽**的错：

> 用户在第三轮说过"我对海鲜过敏"，压缩时被丢了 →
> 第七轮讨论尿酸饮食时，系统建议"可以吃点海产品"。

**没有任何报错**，而且看起来还很合理。所以"永不丢弃"要**按字段结构保护**，
不能靠"摘要写得仔细一点"。

### ③ 谁来压缩：规则 还是 模型

| | 规则（`rule`） | 模型（`model`） |
|---|---|---|
| 可复现 | ✅ 完全确定 | ❌ 每次摘要可能不同 |
| 成本 | 免费 | 每压缩一次一次调用 |
| 质量 | 粗糙（截断+拼接） | 好（真能概括） |
| 可测 | ✅ 能写断言 | 难 |

**注意**：这一层的不可复现**不会**污染审计数字——
因为审计结论是**冻结**的（见下面第四条），压缩只影响"对话怎么表达"。

### ④ 对话能不能改审计结论

**我的建议是：绝对不能，而且我已经把它做成了硬约束**（`frozen_audit` 没有 setter，有测试守着）。

理由：如果能改，那"这份报告被判有问题"就取决于用户跟你聊了什么——
**审计器的可复现性就没了**，简历上那个 87.9% 也就站不住了。

**方向必须是单向的：审计结论 → 对话（只读）。**
你可以挑战这条，但要先想清楚代价。

### ⑤ 会话留存与删除

体检数据是敏感个人信息。会话里会有"用户问了什么指标、什么症状"。
**留存多久、怎么删、删了以后审计日志还在不在**——这是合规判断，不是工程判断。
"""

from __future__ import annotations

from dataclasses import dataclass, field

__all__ = [
    "ALWAYS_KEEP",
    "CHAT_POLICY",
    "CHAT_PROMPT",
    "ChatPolicy",
]


# ============================================================================
# ① + ② + ③ + ⑤：策略本体
# ============================================================================


@dataclass(frozen=True)
class ChatPolicy:
    """上下文管理的全部策略。**每一项都是判断，不是默认值。**"""

    # ---- 单位约定（先把这件事说清，否则所有数字都是错的）----
    #
    # **一轮 = 一次问答（用户问 + 助手答），不是一条消息。**
    #
    # 两边的区别会让所有阈值差 2 倍。之所以选"一次问答"：
    #
    # 1. **问答是不可分割的语义单元**——保留问题却丢掉答案，用户看不到有用上下文
    # 2. **消息数可能是奇数**（模型调用失败时只剩用户那句）——
    #    按"条"保留会把一对问答劈开，留下一个**没有答案的问题**
    #
    # 所以字段名里带 `exchange`（次问答），代码里也按**成对**切。

    # ---- ① 压缩触发 ----
    keep_recent_exchanges: int = 3
    """压缩时**保留最近几次问答的原文**。更早的才会被压成摘要。

    太小 → 代词和追问会失去指代对象（"那我要复查吗"里的"那"指什么？）
    太大 → 压缩没意义。
    """

    max_exchanges_before_compact: int = 6
    """**超过几次问答就触发压缩。** 设得越小越省钱但越容易丢上下文。"""

    context_char_budget: int = 6000
    """送进模型的上下文字符上限（不含冻结的审计结论）。

    这是一个**成本旋钮**：它直接决定每轮发多少字给模型。
    """

    # ---- ③ 谁来压缩 ----
    compact_mode: str = "rule"
    """"rule"（确定性、免费、可测）/ "model"（质量好、花钱、不可复现）/ "off"（不压缩）。

    ⚠️ 选 "off" 会让上下文无限增长——**只适合短会话**。
    """

    # ---- ② 永不丢弃 ----
    always_keep: tuple[str, ...] = (
        "profile",        # 性别 / 年龄 —— 影响所有判定，丢了会算错
        "frozen_audit",   # 审计结论 —— 对话只能读，不能改
        "pinned",         # 用户明确要求记住的事（过敏史、长期用药…）
    )
    """**结构上**永不参与压缩的字段。

    ⚠️ 这里是**字段名**，不是"内容摘要"。靠摘要保不住东西——
    摘要"写得仔细"是不可验证的承诺，字段保护是可测的。
    """

    compact_keep_user_questions: bool = True
    """压缩时，用户**问过什么**是否保留（我认为该保留：它定义了这个会话在聊什么）。"""

    compact_summary_chars: int = 1200
    """压缩摘要的字符上限。超了就截断——**截断时必须留下"有东西被截断了"的标记**。"""

    # ---- ⑤ 留存 ----
    session_retention_days: int = 0
    """会话留存天数。**0 表示"不自动删除"**——但那意味着数据一直留着。

    ⚠️ 医疗相关数据不留存期限，是合规问题。**这一项必须由你来定，并且写清理由。**
    """

    def __post_init__(self) -> None:
        if self.keep_recent_exchanges < 1:
            raise ValueError(
                "keep_recent_exchanges 至少是 1——保留 0 次问答等于把对话全丢了"
            )
        if self.max_exchanges_before_compact < self.keep_recent_exchanges:
            raise ValueError(
                f"max_exchanges_before_compact({self.max_exchanges_before_compact}) "
                f"不能小于 keep_recent_exchanges({self.keep_recent_exchanges})——"
                "那样一压缩就把刚说过的话也压掉了"
            )
        if self.context_char_budget < 200:
            raise ValueError("context_char_budget 太小了，几乎发不出任何上下文")
        if self.compact_mode not in ("rule", "model", "off"):
            raise ValueError(f"compact_mode 只能是 rule/model/off，收到 {self.compact_mode!r}")
        if not self.always_keep:
            raise ValueError(
                "always_keep 不能为空——至少要保住 frozen_audit，"
                "否则对话可以改审计结论"
            )
        if "frozen_audit" not in self.always_keep:
            raise ValueError(
                "frozen_audit 必须在 always_keep 里。\n"
                "  审计结论一旦被对话改写，'同一份报告永远得到同一个结论'这条就没了，\n"
                "  简历上的召回率也不再是确定的数字。"
            )
        if self.session_retention_days < 0:
            raise ValueError("session_retention_days 不能是负数")

    @property
    def retention_label(self) -> str:
        if self.session_retention_days == 0:
            return "**不自动删除**（需要你确认这是可接受的）"
        return f"{self.session_retention_days} 天后可清理"

    @property
    def compact_label(self) -> str:
        return {
            "rule": "规则压缩（确定、免费、可测）",
            "model": "模型压缩（质量好、花钱、不可复现）",
            "off": "不压缩（上下文无限增长，只适合短会话）",
        }[self.compact_mode]


CHAT_POLICY = ChatPolicy()


