"""★ 这是你的文件 ★ LLM 两级的提示词：查询改写 与 重排。

机制在 `rag/llm_stages.py`（解析、缓存、错误计数），**内容在这里**。
和 `agent/prompts.py` 同一个约定：改完跑评测看数字，不要凭感觉。

## 为什么这两级重要

BM25 的硬伤是**词汇不匹配**：
用户说"吃药"，文档写"干预"；用户说"转氨酶"，文档写"丙氨酸氨基转移酶"。

- **查询改写**：把口语问句扩成检索词，让 BM25 有机会匹配上
- **重排**：把召回的 10 条交给模型排序，它比 BM25 更懂"哪条真的在回答这个问题"

## 两条必须守住的纪律

**① 输出格式必须能被程序解析，解析失败算错误。**

不要用"如果模型没按格式就猜一下"的写法——那等于把失败伪装成成功。
项目里已经吃过这个亏：解析失败被当成"没有越界"，是最危险的失败模式。

**② 改写要"加词"，不要"换题"。**

如果改写把原问题的意思改掉了，召回会跑偏——而**跑偏了也看不出来**（分数可能还涨）。
所以提示词里要明确："只补充同义词和检索词，不要改变问题本身"。
"""

from __future__ import annotations

__all__ = ["RERANK_PROMPT", "REWRITE_PROMPT"]


REWRITE_PROMPT = """你在帮一个医学检验解读知识库做检索。用户的问题常常很口语化，而知识库里的说法更正式。

请把下面这个问题**补充成更适合检索的词**，规则：

1. **只补充同义词、缩写、全称、相关说法**，不要改变问题本身的意思
2. 不要回答问题，不要给建议，只给检索词
3. 最多 8 个词，词要短（每个不超过 10 个字）
4. 如果问题里有指标名，把它的**全称和缩写都列出来**
5. 不要编造问题里没有涉及的疾病或药物

用户问题：
{query}

只输出一个 JSON，不要任何其他文字：
{{"terms": ["词1", "词2", "词3"]}}
"""


