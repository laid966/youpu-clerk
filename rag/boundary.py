# ============================================================================
# ① 拒答边界
# ============================================================================


@dataclass(frozen=True)
class RefusalBoundary:
    min_top_score: float = 1.0
    """最高检索分低于这个值 → 拒答。

    BM25 的分数没有绝对含义（它取决于语料和词表），所以这个数**要试出来**：
    跑 `python -m rag eval --refusal`，看拒答正确率和误伤率怎么随它变。
    """

    min_hits: int = 1
    """至少要命中几条才允许回答。"""

    refuse_message: str = "知识库中没有找到与该问题相关的依据，因此不作回答。"

    def __post_init__(self) -> None:
        if self.min_top_score < 0:
            raise ValueError("min_top_score 不能是负数——那样等于永不拒答")
        if self.min_hits < 1:
            raise ValueError("min_hits 至少是 1")

    def should_refuse(self, scores: Sequence[float]) -> bool:
        """给一串检索分（已按高低排序），判断该不该拒答。"""
        if len(scores) < self.min_hits:
            return True
        return scores[0] < self.min_top_score


REFUSAL = RefusalBoundary()


# ============================================================================
# ② 什么算"答对"
# ============================================================================


@dataclass(frozen=True)
class CorrectnessRule:
    strict: bool = True
    """True = 必须命中标准答案那一条；False = 命中同一层任意 chunk 也算对。"""

    tolerant_layers: tuple[str, ...] = ("explanation", "guideline")
    """宽松口径下，算数的层。**只在 strict=False 时生效。**"""

    def __post_init__(self) -> None:
        if not self.strict and not self.tolerant_layers:
            raise ValueError("宽松口径必须声明哪些层算数，否则等于「全都算对」")

    @property
    def label(self) -> str:
        return "严格：必须命中标准答案那一条" if self.strict else (
            f"宽松：命中 {'/'.join(self.tolerant_layers)} 层任意一条即算对"
        )


CORRECTNESS = CorrectnessRule()


