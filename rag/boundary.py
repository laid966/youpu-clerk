"""★ 这是你的文件 ★ RAG 的**边界定义**与**判定口径**。

这份文件里的每一个数都在回答"什么算对、什么算错"，**这是产品判断，不是技术判断**，
所以由你填。我只提供机制和默认值。

## 你要决定的三件事

### ① 拒答边界：什么情况下必须承认"知识库没有依据"

宁可说"不知道"，也不能硬答——这是这个项目的红线：
**没有依据的回答比不回答更危险**（它看起来同样自信）。

但阈值是一个**真实的取舍**：

| 阈值调松 | 阈值调紧 |
|---|---|
| 少漏答（该答的答了） | 少硬答（不该答的不答） |
| 但**误伤**：库内问题被拒答 | 但**漏答**：库外问题被硬答 |

**所以评测会同时给你两个数**（拒答正确率 / 拒答误伤率），
你调完阈值看这两个数一起动，而不是只看一个。

### ② 什么算"答对"

检索评测要判定"这条问句答对了没有"。判定口径不同，分数就完全不同：

- **严格口径（默认）**：命中的 chunk 必须是标准答案那一条
- **宽松口径**：命中同一层的任意 chunk 就算对

⚠️ **宽松口径会让分数虚高，而且和历史基线不可比。**
要改成宽松，请在下面写清理由——面试官会问"你这个 Recall@1 是怎么算的"。

### ③ 意图路由：什么问法该去查哪一层

L2 指标解释库回答"这个指标是什么、为什么高"；
L3 指南要点库回答"该怎么办、复查怎么准备"。

问句里出现哪些词应该优先走哪一层——这属于**领域知识**，
我给的只是起步的几个词，你按真实问法补。
"""

